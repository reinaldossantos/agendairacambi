create or replace function public.initialize_purchase_request_approval(target_request_id uuid)
returns void language plpgsql security definer set search_path=public as $$
declare r public.purchase_requests%rowtype; actor uuid:=public.current_person_id(); rid uuid; tid uuid; required uuid[]; recipient uuid;
begin
  select * into r from public.purchase_requests where id=target_request_id for update;
  if r.id is null then raise exception 'Solicitação não encontrada.'; end if;
  if actor is null or actor is distinct from r.requester_id then raise exception 'Somente o solicitante pode enviar esta solicitação.'; end if;
  if r.status not in ('draft','changes_requested') then raise exception 'Esta solicitação não pode ser enviada neste estado.'; end if;
  if nullif(trim(r.title),'') is null or nullif(trim(r.justification),'') is null or jsonb_array_length(r.items)=0 then raise exception 'Informe título, justificativa e ao menos um item.'; end if;
  select person_id into rid from public.expense_approval_config where approver_key='reinaldo' and is_active;
  select person_id into tid from public.expense_approval_config where approver_key='thais' and is_active;
  if rid is null or tid is null then raise exception 'Configure Reinaldo e Thaís como aprovadores.'; end if;
  required:=case when actor=rid then array[tid] when actor=tid then array[rid] else array[rid,tid] end;
  delete from public.purchase_request_approvals where request_id=target_request_id;
  insert into public.purchase_request_approvals(request_id,approver_id) select target_request_id,unnest(required);
  update public.purchase_requests set status='pending_approval',submitted_at=now(),approved_at=null where id=target_request_id;
  insert into public.purchase_request_history(request_id,actor_id,event_type,content) values(target_request_id,actor,'submitted','Solicitação enviada para aprovação.');
  foreach recipient in array required loop
    insert into public.purchase_request_notifications(request_id,recipient_id,actor_id,type,title,content)
    values(target_request_id,recipient,actor,'approval_requested','Nova solicitação de compra','A solicitação nº '||lpad(r.request_number::text,5,'0')||' aguarda sua análise.');
  end loop;
end $$;

-- Linha do tempo operacional imutável: cada passo da equipe permanece individualizado.
create table if not exists public.purchase_request_steps (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.purchase_requests(id) on delete cascade,
  actor_id uuid not null references public.persons(id) on delete restrict,
  step_type text not null check (step_type in (
    'comment','quotation_requested','quotation_received','supplier_selected','order_issued',
    'invoice_received','payment_scheduled','payment_completed','partial_receipt','receipt_completed','document_added'
  )),
  title text not null,
  description text,
  supplier_name text,
  document_number text,
  amount numeric(14,2) check (amount is null or amount >= 0),
  event_date date not null default current_date,
  attachments jsonb not null default '[]'::jsonb check (jsonb_typeof(attachments)='array'),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists purchase_steps_request_idx on public.purchase_request_steps(request_id,created_at desc);
alter table public.purchase_request_steps enable row level security;
drop policy if exists purchase_steps_active_read on public.purchase_request_steps;
create policy purchase_steps_active_read on public.purchase_request_steps for select to authenticated using (public.is_active_user());
grant select on public.purchase_request_steps to authenticated;

create or replace function public.record_purchase_request_step(
  target_request_id uuid, requested_step_type text, step_title text, step_description text default null,
  step_supplier_name text default null, step_document_number text default null, step_amount numeric default null,
  step_event_date date default current_date, step_attachments jsonb default '[]'::jsonb
) returns uuid language plpgsql security definer set search_path=public as $$
declare actor uuid:=public.current_person_id(); r public.purchase_requests%rowtype; new_id uuid; resulting_status text;
begin
  if actor is null or not public.is_active_user() then raise exception 'Usuário sem acesso ativo.'; end if;
  if requested_step_type not in ('comment','quotation_requested','quotation_received','supplier_selected','order_issued','invoice_received','payment_scheduled','payment_completed','partial_receipt','receipt_completed','document_added') then raise exception 'Tipo de etapa inválido.'; end if;
  if nullif(trim(step_title),'') is null then raise exception 'Informe o título do registro.'; end if;
  select * into r from public.purchase_requests where id=target_request_id for update;
  if r.id is null then raise exception 'Solicitação não encontrada.'; end if;
  if requested_step_type not in ('comment','document_added') and not public.is_admin() and not exists(select 1 from public.expense_approval_config where person_id=actor and is_active) then raise exception 'Etapa restrita aos responsáveis pelo processo de compras.'; end if;
  if requested_step_type in ('quotation_received','supplier_selected') and nullif(trim(step_supplier_name),'') is null then raise exception 'Informe o fornecedor.'; end if;
  if requested_step_type in ('order_issued','invoice_received') and nullif(trim(step_document_number),'') is null then raise exception 'Informe o número do documento.'; end if;
  if jsonb_typeof(coalesce(step_attachments,'[]'::jsonb))<>'array' then raise exception 'Anexos inválidos.'; end if;

  insert into public.purchase_request_steps(request_id,actor_id,step_type,title,description,supplier_name,document_number,amount,event_date,attachments)
  values(target_request_id,actor,requested_step_type,trim(step_title),nullif(trim(step_description),''),nullif(trim(step_supplier_name),''),nullif(trim(step_document_number),''),step_amount,coalesce(step_event_date,current_date),coalesce(step_attachments,'[]'::jsonb)) returning id into new_id;

  resulting_status:=case requested_step_type
    when 'quotation_received' then 'quotation' when 'supplier_selected' then 'quotation'
    when 'order_issued' then 'ordered' when 'partial_receipt' then 'partially_received'
    when 'receipt_completed' then 'received' else null end;
  if resulting_status is not null then
    update public.purchase_requests set status=resulting_status,
      ordered_at=case when resulting_status='ordered' then now() else ordered_at end,
      received_at=case when resulting_status='received' then now() else received_at end
    where id=target_request_id;
  end if;
  insert into public.purchase_request_history(request_id,actor_id,event_type,content,metadata)
  values(target_request_id,actor,'operational_step',trim(step_title),jsonb_build_object('step_id',new_id,'step_type',requested_step_type,'status',resulting_status));
  if r.requester_id<>actor then
    insert into public.purchase_request_notifications(request_id,recipient_id,actor_id,type,title,content)
    values(target_request_id,r.requester_id,actor,'operational_step','Movimentação na solicitação de compra','Novo registro em '||lpad(r.request_number::text,5,'0')||': '||trim(step_title));
  end if;
  return new_id;
end $$;
revoke all on function public.record_purchase_request_step(uuid,text,text,text,text,text,numeric,date,jsonb) from public;
grant execute on function public.record_purchase_request_step(uuid,text,text,text,text,text,numeric,date,jsonb) to authenticated;

do $$ begin
  if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='purchase_request_steps') then alter publication supabase_realtime add table public.purchase_request_steps; end if;
end $$;

create or replace function public.decide_purchase_request(target_request_id uuid,requested_decision text,decision_comment text default null)
returns text language plpgsql security definer set search_path=public as $$
declare actor uuid:=public.current_person_id(); actor_name text; r public.purchase_requests%rowtype; pending integer; resulting text;
begin
  if requested_decision not in ('approved','changes_requested','rejected') then raise exception 'Decisão inválida.'; end if;
  if requested_decision<>'approved' and nullif(trim(decision_comment),'') is null then raise exception 'Informe a justificativa da decisão.'; end if;
  select * into r from public.purchase_requests where id=target_request_id for update;
  select name into actor_name from public.persons where id=actor;
  if r.id is null then raise exception 'Solicitação não encontrada.'; end if;
  if actor=r.requester_id then raise exception 'O solicitante não pode aprovar a própria solicitação.'; end if;
  update public.purchase_request_approvals set decision=requested_decision,comment=nullif(trim(decision_comment),''),decided_at=now()
    where request_id=target_request_id and approver_id=actor and decision='pending';
  if not found then raise exception 'Você não possui aprovação pendente para esta solicitação.'; end if;
  if requested_decision in ('rejected','changes_requested') then resulting:=requested_decision;
  else select count(*) into pending from public.purchase_request_approvals where request_id=target_request_id and decision='pending'; resulting:=case when pending=0 then 'approved' else 'pending_approval' end; end if;
  update public.purchase_requests set status=resulting,approved_at=case when resulting='approved' then now() else null end where id=target_request_id;
  insert into public.purchase_request_history(request_id,actor_id,event_type,content,metadata)
    values(target_request_id,actor,requested_decision,coalesce(nullif(trim(decision_comment),''),actor_name||' aprovou a solicitação.'),jsonb_build_object('status',resulting));
  insert into public.purchase_request_notifications(request_id,recipient_id,actor_id,type,title,content)
    values(target_request_id,r.requester_id,actor,resulting,case resulting when 'approved' then 'Solicitação aprovada' when 'pending_approval' then 'Aprovação parcial' when 'changes_requested' then 'Ajustes solicitados' else 'Solicitação reprovada' end,'A solicitação nº '||lpad(r.request_number::text,5,'0')||' foi analisada por '||actor_name||'.');
  return resulting;
end $$;

create or replace function public.advance_purchase_request(target_request_id uuid,next_status text,transition_comment text default null)
returns void language plpgsql security definer set search_path=public as $$
declare actor uuid:=public.current_person_id(); current_status text; requester uuid; request_no bigint;
begin
  if not public.is_admin() and not exists(select 1 from public.expense_approval_config where person_id=actor and is_active) then raise exception 'Operação restrita aos responsáveis por compras.'; end if;
  select status,requester_id,request_number into current_status,requester,request_no from public.purchase_requests where id=target_request_id for update;
  if not ((current_status='approved' and next_status in ('quotation','ordered','cancelled')) or (current_status='quotation' and next_status in ('ordered','cancelled')) or (current_status='ordered' and next_status in ('partially_received','received','cancelled')) or (current_status='partially_received' and next_status in ('received','cancelled'))) then raise exception 'Transição de situação inválida.'; end if;
  update public.purchase_requests set status=next_status,ordered_at=case when next_status='ordered' then now() else ordered_at end,received_at=case when next_status='received' then now() else received_at end where id=target_request_id;
  insert into public.purchase_request_history(request_id,actor_id,event_type,content,metadata) values(target_request_id,actor,'status',coalesce(nullif(trim(transition_comment),''),'Situação alterada para '||next_status||'.'),jsonb_build_object('from',current_status,'to',next_status));
  insert into public.purchase_request_notifications(request_id,recipient_id,actor_id,type,title,content) values(target_request_id,requester,actor,next_status,'Atualização da solicitação de compra','A solicitação nº '||lpad(request_no::text,5,'0')||' avançou para: '||next_status||'.');
end $$;

