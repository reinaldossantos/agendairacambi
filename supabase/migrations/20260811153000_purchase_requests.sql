-- Solicitações de compras. Migração versionada; aplicada com Supabase CLI após project_management.sql
-- e expense_report_approvals.sql.

create table if not exists public.purchase_requests (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated by default as identity unique,
  requester_id uuid not null references public.persons(id) on delete restrict,
  title text not null,
  request_type text not null default 'goods' check (request_type in ('goods','services','works')),
  urgency text not null default 'normal' check (urgency in ('low','normal','high','critical')),
  status text not null default 'draft' check (status in ('draft','pending_approval','changes_requested','rejected','approved','quotation','ordered','partially_received','received','cancelled')),
  justification text not null,
  needed_by date,
  management_project_id uuid references public.management_projects(id) on delete set null,
  edital_name text, edital_number text, edital_deadline date, funding_source text,
  program_ids uuid[] not null default '{}',
  beneficiary_person_ids uuid[] not null default '{}',
  beneficiary_description text, supplier_suggestion text, delivery_location text,
  items jsonb not null default '[]'::jsonb check (jsonb_typeof(items) = 'array'),
  estimated_total numeric(14,2) not null default 0 check (estimated_total >= 0),
  attachments jsonb not null default '[]'::jsonb check (jsonb_typeof(attachments) = 'array'),
  submitted_at timestamptz, approved_at timestamptz, ordered_at timestamptz, received_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check (edital_deadline is null or edital_name is not null),
  check (status = 'draft' or jsonb_array_length(items) > 0)
);

create table if not exists public.purchase_request_approvals (
  id uuid primary key default gen_random_uuid(), request_id uuid not null references public.purchase_requests(id) on delete cascade,
  approver_id uuid not null references public.persons(id) on delete restrict,
  decision text not null default 'pending' check (decision in ('pending','approved','changes_requested','rejected')),
  comment text, decided_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(request_id, approver_id)
);
create table if not exists public.purchase_request_history (
  id bigint generated always as identity primary key, request_id uuid not null references public.purchase_requests(id) on delete cascade,
  actor_id uuid references public.persons(id) on delete set null, event_type text not null, content text not null,
  metadata jsonb not null default '{}'::jsonb, created_at timestamptz not null default now()
);
create table if not exists public.purchase_request_notifications (
  id uuid primary key default gen_random_uuid(), request_id uuid not null references public.purchase_requests(id) on delete cascade,
  recipient_id uuid not null references public.persons(id) on delete cascade, actor_id uuid references public.persons(id) on delete set null,
  type text not null, title text not null, content text not null, read_at timestamptz, created_at timestamptz not null default now()
);

create index if not exists purchase_requests_status_idx on public.purchase_requests(status,created_at desc);
create index if not exists purchase_requests_requester_idx on public.purchase_requests(requester_id,created_at desc);
create index if not exists purchase_requests_project_idx on public.purchase_requests(management_project_id);
create index if not exists purchase_requests_programs_idx on public.purchase_requests using gin(program_ids);
create index if not exists purchase_approvals_approver_idx on public.purchase_request_approvals(approver_id,decision);
create index if not exists purchase_history_request_idx on public.purchase_request_history(request_id,created_at desc);
create index if not exists purchase_notifications_recipient_idx on public.purchase_request_notifications(recipient_id,read_at,created_at desc);

drop trigger if exists purchase_requests_updated_at on public.purchase_requests;
create trigger purchase_requests_updated_at before update on public.purchase_requests for each row execute function public.set_updated_at();
drop trigger if exists purchase_approvals_updated_at on public.purchase_request_approvals;
create trigger purchase_approvals_updated_at before update on public.purchase_request_approvals for each row execute function public.set_updated_at();

