-- As tabelas deixam de ser acessíveis com a chave pública sem uma sessão autenticada.
revoke all privileges on all tables in schema public from anon;
revoke all privileges on all sequences in schema public from anon;
grant usage on schema public to authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
alter default privileges in schema public revoke all on tables from anon;
alter default privileges in schema public grant select, insert, update, delete on tables to authenticated;

alter table public.user_access_logs enable row level security;
alter table public.security_notifications enable row level security;

drop policy if exists "admins_read_access_logs" on public.user_access_logs;
drop policy if exists "reinaldo_reads_access_logs" on public.user_access_logs;
create policy "reinaldo_reads_access_logs" on public.user_access_logs for select to authenticated using (
  exists (select 1 from public.persons where auth_user_id = auth.uid() and lower(email) = 'reinaldo@iracambi.com')
);
drop policy if exists "users_read_security_notifications" on public.security_notifications;
create policy "users_read_security_notifications" on public.security_notifications for select to authenticated using (
  recipient_id in (select id from public.persons where auth_user_id = auth.uid())
);
drop policy if exists "users_update_security_notifications" on public.security_notifications;
create policy "users_update_security_notifications" on public.security_notifications for update to authenticated using (
  recipient_id in (select id from public.persons where auth_user_id = auth.uid())
);
