-- Autenticação e controle de acesso dos usuários da Agenda Iracambi.
alter table public.persons
  add column if not exists email text,
  add column if not exists auth_user_id uuid references auth.users(id) on delete set null,
  add column if not exists access_role text not null default 'user' check (access_role in ('user', 'admin')),
  add column if not exists must_change_password boolean not null default true,
  add column if not exists failed_login_attempts integer not null default 0,
  add column if not exists locked_at timestamptz,
  add column if not exists last_login_at timestamptz,
  add column if not exists managed_by uuid references public.persons(id) on delete set null;

create unique index if not exists persons_email_unique_idx on public.persons (lower(email)) where email is not null;
create index if not exists persons_auth_user_idx on public.persons(auth_user_id);

create table if not exists public.user_access_logs (
  id bigint generated by default as identity primary key,
  person_id uuid references public.persons(id) on delete set null,
  email text not null,
  event_type text not null check (event_type in ('login_success', 'login_failure', 'account_locked', 'logout', 'password_changed', 'password_reset')),
  user_agent text,
  occurred_at timestamptz not null default now(),
  session_id uuid,
  last_seen_at timestamptz,
  ended_at timestamptz,
  duration_seconds integer not null default 0,
  ip_address inet
);

create table if not exists public.security_notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.persons(id) on delete cascade,
  person_id uuid references public.persons(id) on delete set null,
  type text not null,
  title text not null,
  content text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

